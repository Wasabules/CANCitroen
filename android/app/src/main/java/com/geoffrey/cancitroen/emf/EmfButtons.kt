package com.geoffrey.cancitroen.emf

/**
 * Mapping des boutons EMF émulés sur la trame 0x3E5 (DLC=6).
 * Source : github.com/morcibacsi/PSAWifiDisplayControl src/Can/Structs/CanMenuStructs.h
 *
 * Structure 6 octets :
 *   byte[0] = MenuField  : bit 0=aircon, bit 4=phone, bit 6=MENU
 *   byte[1] = ModeField  : bit 0=audio, bit 4=MODE, bit 6=TRIP
 *   byte[2] = EscOkField : bit 2=DARK, bit 4=ESC, bit 6=OK
 *   byte[3..4] = (réservés)
 *   byte[5] = ArrowsField: bit 0=LEFT, bit 2=RIGHT, bit 4=DOWN, bit 6=UP
 */
enum class EmfButton(val payload: ByteArray) {
    MENU(  byteArrayOf(0x40, 0x00, 0x00, 0x00, 0x00, 0x00)),
    MODE(  byteArrayOf(0x00, 0x10, 0x00, 0x00, 0x00, 0x00)),
    TRIP(  byteArrayOf(0x00, 0x40, 0x00, 0x00, 0x00, 0x00)),
    OK(    byteArrayOf(0x00, 0x00, 0x40, 0x00, 0x00, 0x00)),
    ESC(   byteArrayOf(0x00, 0x00, 0x10, 0x00, 0x00, 0x00)),
    UP(    byteArrayOf(0x00, 0x00, 0x00, 0x00, 0x00, 0x40)),
    DOWN(  byteArrayOf(0x00, 0x00, 0x00, 0x00, 0x00, 0x10)),
    LEFT(  byteArrayOf(0x00, 0x00, 0x00, 0x00, 0x00, 0x01)),
    RIGHT( byteArrayOf(0x00, 0x00, 0x00, 0x00, 0x00, 0x04)),
    PHONE( byteArrayOf(0x10, 0x00, 0x00, 0x00, 0x00, 0x00)),
    AIRCON(byteArrayOf(0x01, 0x00, 0x00, 0x00, 0x00, 0x00)),
    DARK(  byteArrayOf(0x00, 0x00, 0x04, 0x00, 0x00, 0x00));

    companion object {
        val RELEASE = byteArrayOf(0x00, 0x00, 0x00, 0x00, 0x00, 0x00)
    }
}
